#!/usr/bin/env php
<?php

/**
 * Rebuild registry/mapping.json from the target site.
 *
 * Run this when templates are added or renamed, or when pointing the tooling
 * at a different Archipelago. It matches each repo file to a Metadata Display
 * entity by normalised name -- lowercased, punctuation stripped, any trailing
 * UUID removed from the filename.
 *
 * Names in this repo do not reliably match the site, so an alias table handles
 * the exceptions (a "Presenation" typo, a singular/plural mismatch). Aliases
 * already in the mapping file are PRESERVED, so a fix you make by hand is not
 * lost the next time this runs.
 *
 * Anything still unmatched is written to unmapped_files rather than guessed at.
 * A wrong mapping produces fake drift forever; an honest gap produces one line
 * of output that someone can act on.
 *
 * Usage:
 *   php tools/twig-live/bin/generate-mapping.php [options]
 *
 * Options:
 *   --out=<file>   Where to write. Default registry/mapping.json.
 *   --dry-run      Print what would change, write nothing.
 *   --help
 *
 * Environment:
 *   ARCHIPELAGO_URL, ARCHIPELAGO_USER, ARCHIPELAGO_PASS
 *
 * Exit code 0 = written, 2 = could not run.
 */

declare(strict_types=1);

use Tamu\ArchipelagoLive\Client;

require __DIR__ . '/../src/Client.php';

$options = [
    'out' => __DIR__ . '/../registry/mapping.json',
    'dry-run' => false,
];

foreach (array_slice($argv, 1) as $arg) {
    if ($arg === '--help' || $arg === '-h') {
        fwrite(STDOUT, extractDocblock(__FILE__));
        exit(0);
    }
    if ($arg === '--dry-run') {
        $options['dry-run'] = true;
        continue;
    }
    if (str_starts_with($arg, '--out=')) {
        $options['out'] = substr($arg, 6);
        continue;
    }
    fwrite(STDERR, "Unknown option: {$arg}\n");
    exit(2);
}

$repoRoot = realpath(__DIR__ . '/../../..');
if ($repoRoot === false) {
    fwrite(STDERR, "Could not resolve repository root.\n");
    exit(2);
}

try {
    $client = Client::fromEnvironment();
    $entities = $client->metadataDisplays();
} catch (RuntimeException $e) {
    fwrite(STDERR, $e->getMessage() . "\n");
    exit(2);
}

$existing = is_file($options['out'])
    ? (json_decode((string) file_get_contents($options['out']), true) ?: [])
    : [];

/** @var array<string, string> $aliases */
$aliases = is_array($existing['aliases'] ?? null) ? $existing['aliases'] : [];

$byName = [];
foreach ($entities as $entity) {
    $byName[normaliseName($entity['name'])] = $entity;
}

$directory = $repoRoot . '/twig/metadatadisplays';
$files = glob($directory . '/*.twig.html') ?: [];
sort($files);

$templates = [];
$unmapped = [];
$claimed = [];

foreach ($files as $path) {
    $file = basename($path);
    $base = substr($file, 0, -strlen('.twig.html'));

    // An alias wins; otherwise strip a trailing UUID, which some filenames
    // carry as an export artefact.
    $target = $aliases[$base]
        ?? (string) preg_replace('/-[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/', '', $base);

    $entity = $byName[normaliseName($target)] ?? null;

    if ($entity === null) {
        $unmapped[] = $file;
        continue;
    }

    $claimed[$entity['uuid']] = true;
    $templates[$file] = [
        'uuid' => $entity['uuid'],
        'id' => $entity['id'],
        'name' => $entity['name'],
    ];
}

$orphans = [];
foreach ($entities as $entity) {
    if (!isset($claimed[$entity['uuid']])) {
        $orphans[] = $entity['name'];
    }
}

$mapping = [
    '_comment' => [
        'Maps repo template files to the Metadata Display entities they are copies of.',
        'Generated by bin/generate-mapping.php; committed on purpose so drift-check does',
        'not have to guess. Filenames do NOT reliably match entity names -- the repo has',
        'IIIF_Presenation (typo) and Thumbnails_with_Annotation (singular) -- so fuzzy',
        'matching at runtime would invent drift that is not there. Fix a wrong mapping',
        'here rather than renaming a file someone may be linking to.',
        '',
        'unmapped_files have no entity on this site at all. That is a finding, not a bug',
        'in this file: they exist in the repo and nowhere on the target.',
    ],
    'site' => getenv('ARCHIPELAGO_URL') ?: ($existing['site'] ?? ''),
    'generated' => gmdate('c'),
    'aliases' => $aliases,
    'templates' => $templates,
    'unmapped_files' => $unmapped,
    'entities_without_file' => $orphans,
];

$json = json_encode($mapping, JSON_PRETTY_PRINT | JSON_UNESCAPED_SLASHES) . "\n";

printf(
    "%d file%s mapped, %d unmapped, %d entit%s on the site with no file.\n",
    count($templates),
    count($templates) === 1 ? '' : 's',
    count($unmapped),
    count($orphans),
    count($orphans) === 1 ? 'y' : 'ies',
);

foreach ($unmapped as $file) {
    printf("  unmapped file      %s\n", $file);
}
foreach ($orphans as $name) {
    printf("  entity with no file  %s\n", $name);
}

if ($unmapped !== []) {
    fwrite(STDOUT, "\nTo map one of those, add an alias (filename without .twig.html => entity name)\n");
    fwrite(STDOUT, "to the 'aliases' object in the mapping file and run this again.\n");
}

if ($options['dry-run']) {
    fwrite(STDOUT, "\n--dry-run: nothing written.\n");
    exit(0);
}

if (file_put_contents($options['out'], $json) === false) {
    fwrite(STDERR, "Could not write {$options['out']}\n");
    exit(2);
}

printf("\nWrote %s\n", $options['out']);
exit(0);

// ---------------------------------------------------------------------------

function normaliseName(string $value): string
{
    return (string) preg_replace('/[^a-z0-9]/', '', strtolower($value));
}

function extractDocblock(string $file): string
{
    $contents = (string) file_get_contents($file);
    if (preg_match('#/\*\*(.*?)\*/#s', $contents, $matches) !== 1) {
        return "No help available.\n";
    }

    return trim((string) preg_replace('/^\s*\* ?/m', '', $matches[1])) . "\n";
}
